// Writes server/db/migrations.generated.ts: the SQL migrations as data, for
// runtimes without a filesystem (the Supabase Edge Function). Each entry has
// exactly the shape drizzle's migrator reads from disk (statements split on
// breakpoints, journal timestamp, sha256 of the file), so Node and the edge
// share one migrations table. Run by `npm run db:generate`; CI checks it.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const dir = new URL('../server/db/migrations/', import.meta.url);
const journal = JSON.parse(readFileSync(new URL('meta/_journal.json', dir), 'utf8'));
const migrations = journal.entries.map((entry) => {
  const query = readFileSync(new URL(`${entry.tag}.sql`, dir), 'utf8');
  return { tag: entry.tag, sql: query.split('--> statement-breakpoint'), bps: entry.breakpoints, folderMillis: entry.when, hash: createHash('sha256').update(query).digest('hex') };
});

const out = `// Generated by scripts/embed-migrations.mjs from server/db/migrations. Do not edit.
export interface EmbeddedMigration {
  tag: string;
  sql: string[];
  bps: boolean;
  folderMillis: number;
  hash: string;
}

export const MIGRATIONS: EmbeddedMigration[] = ${JSON.stringify(migrations, null, 2)};
`;
const target = new URL('../server/db/migrations.generated.ts', import.meta.url);
if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(target, 'utf8');
  } catch {
    /* missing */
  }
  if (current !== out) {
    console.error('server/db/migrations.generated.ts is out of date. Run: node scripts/embed-migrations.mjs');
    process.exit(1);
  }
  console.log(`Embedded migrations up to date (${migrations.length}).`);
} else {
  writeFileSync(target, out);
  console.log(`Embedded ${migrations.length} migrations.`);
}
